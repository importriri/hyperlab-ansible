def write_outputs(
    repo: Path,
    theme_id: str,
    outdir: Path,
    preview: Path | None,
) -> None:
    _manifest, visual = load(repo, theme_id)

    outdir.mkdir(parents=True, exist_ok=True)

    rendered = outputs(visual)

    require(
        tuple(sorted(rendered))
        == tuple(sorted(OUTPUTS)),
        "renderer output set changed",
    )

    for filename, content in rendered.items():
        target = outdir / filename
        target.write_text(content, encoding="utf-8")
        print(target)

    if preview is not None:
        preview.parent.mkdir(parents=True, exist_ok=True)

        # HTML fragments are indented for source readability. Strip only
        # incidental end-of-line whitespace before publishing the canonical
        # preview so generated output is deterministic and diff-clean.
        preview_content = "\n".join(
            line.rstrip(" \t")
            for line in preview_html(repo, visual).splitlines()
        ) + "\n"

        preview.write_text(
            preview_content,
            encoding="utf-8",
        )
        print(preview)


def main() -> int:
    parser = argparse.ArgumentParser()

    parser.add_argument(
        "--repo",
        type=Path,
        default=Path(__file__).resolve().parents[1],
    )
    parser.add_argument("theme")
    parser.add_argument("outdir", type=Path)
    parser.add_argument("--preview", type=Path)

    args = parser.parse_args()

    try:
        write_outputs(
            args.repo,
            args.theme,
            args.outdir,
            args.preview,
        )
        return 0
    except (
        OSError,
        KeyError,
        TypeError,
        ThemeRenderError,
        yaml.YAMLError,
    ) as exc:
        print(
            f"HyperLab theme renderer: {exc}",
            file=sys.stderr,
        )
        return 1


if __name__ == "__main__":
    raise SystemExit(main())
