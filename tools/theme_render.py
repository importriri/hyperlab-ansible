BANNER = "Generated by theme_render.py; do not edit by hand."


class ThemeRenderError(ValueError):
    pass


def require(condition: bool, message: str) -> None:
    if not condition:
        raise ThemeRenderError(message)


def raw(value: str) -> str:
    return value.removeprefix("#")


def load(repo: Path, theme_id: str) -> tuple[dict[str, Any], dict[str, Any]]:
    root = repo / "themes" / theme_id

    manifest = yaml.safe_load(
        (root / "theme.yml").read_text(encoding="utf-8")
    )
    visual = yaml.safe_load(
        (root / "visual.yml").read_text(encoding="utf-8")
    )

    require(manifest["id"] == theme_id, "manifest/theme id mismatch")
    require(visual["theme"] == theme_id, "visual/theme id mismatch")

    trust = visual["trust"]["identities"]

    colours = {
        identity: trust[identity]["color"]
        for identity in TRUST_ORDER
    }

    require(
        colours == EXPECTED_TRUST_COLORS,
        "trust identity colours changed",
    )

    require(
        visual["appearance"]["focus"] == "#d0d7de",
        "generic focus token must remain neutral",
    )

    require(
        visual["keyboard_rgb"]["provider"]
        == "hyperlab-nitro-control",
        "unreviewed RGB provider",
    )

    return manifest, visual


def palette(visual: dict[str, Any]) -> dict[str, str]:
    appearance = visual["appearance"]
    trust = visual["trust"]["identities"]

    return {
        "name": "trust-model",
        "base": appearance["base"],
        "mantle": appearance["mantle"],
        "surface": appearance["surface"],
        "overlay": appearance["overlay"],
        "text": appearance["text"],
        "subtext": appearance["subtext"],
        "accent": appearance["focus"],
        "accent2": appearance["host_neutral"],
        "ok": "#3fb950",
        "warn": "#d29922",
        "bad": "#f85149",
        "dom_host": trust["host"]["color"],
        "dom_clean": trust["clean"]["color"],
        "dom_dev": trust["dev"]["color"],
        "dom_services": trust["services"]["color"],
        "dom_dirty": trust["dirty"]["color"],
        "dom_lab": trust["lab"]["color"],
    }


def quickshell(c: dict[str, str]) -> str:
    return json.dumps(
        c,
        indent=2,
        sort_keys=True,
    ) + "\n"


def css_tokens(c: dict[str, str], consumer: str) -> str:
    tokens = (
        "base",
        "mantle",
        "surface",
        "overlay",
        "text",
        "subtext",
        "accent",
        "accent2",
        "ok",
        "warn",
        "bad",
        "dom_host",
        "dom_clean",
        "dom_dev",
        "dom_services",
        "dom_dirty",
        "dom_lab",
    )

    lines = [
        f"/* {BANNER} theme: trust-model consumer: {consumer} */"
    ]

    lines.extend(
        f"@define-color hl_{token} {c[token]};"
        for token in tokens
    )

    return "\n".join(lines) + "\n"


def rofi(c: dict[str, str]) -> str:
    tokens = (
        "base",
        "mantle",
        "surface",
        "overlay",
        "text",
        "subtext",
        "accent",
        "accent2",
        "ok",
        "warn",
        "bad",
        "dom_host",
        "dom_clean",
        "dom_dev",
        "dom_services",
        "dom_dirty",
        "dom_lab",
    )

    lines = [
        f"/* {BANNER} theme: trust-model */",
        "* {",
    ]

    lines.extend(
        f"    hl-{token.replace('_', '-')}: {c[token]};"
        for token in tokens
    )

    lines.extend(
        [
            "    background-color: transparent;",
            "    text-color: @hl-text;",
            "}",
        ]
    )

    return "\n".join(lines) + "\n"


