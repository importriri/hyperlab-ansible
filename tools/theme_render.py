def hyprland(c: dict[str, str]) -> str:
    lines = [
        f"-- {BANNER} theme: trust-model",
        "return {",
    ]

    for key in (
        "base",
        "mantle",
        "surface",
        "overlay",
        "text",
        "subtext",
        "accent",
        "accent2",
        "ok",
        "warn",
        "bad",
        "dom_host",
        "dom_clean",
        "dom_dev",
        "dom_services",
        "dom_dirty",
        "dom_lab",
    ):
        lines.append(f'    {key} = "{c[key]}",')

    lines.extend(
        [
            f'    active_border = "rgba({raw(c["accent"])}ff)",',
            f'    inactive_border = "rgba({raw(c["overlay"])}ff)",',
            f'    urgent_border = "rgba({raw(c["bad"])}ff)",',
            "}",
        ]
    )

    return "\n".join(lines) + "\n"


def sway(c: dict[str, str]) -> str:
    lines = [
        f"# {BANNER} theme: trust-model",
    ]

    for key in (
        "base",
        "mantle",
        "surface",
        "overlay",
        "text",
        "subtext",
        "accent",
        "accent2",
        "ok",
        "warn",
        "bad",
        "dom_host",
        "dom_clean",
        "dom_dev",
        "dom_services",
        "dom_dirty",
        "dom_lab",
    ):
        lines.append(f"set $hl_{key} {c[key]}")

    lines.extend(
        [
            "",
            "client.focused "
            "$hl_accent $hl_mantle $hl_text "
            "$hl_accent $hl_accent",
            "client.unfocused "
            "$hl_overlay $hl_base $hl_subtext "
            "$hl_overlay $hl_overlay",
            "client.focused_inactive "
            "$hl_overlay $hl_base $hl_subtext "
            "$hl_overlay $hl_overlay",
            "client.urgent "
            "$hl_bad $hl_mantle $hl_text "
            "$hl_bad $hl_bad",
        ]
    )

    return "\n".join(lines) + "\n"


