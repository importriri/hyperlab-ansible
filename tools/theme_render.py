def rgb_map(visual: dict[str, Any]) -> str:
    rgb = visual["keyboard_rgb"]

    payload = {
        "version": 1,
        "theme": "trust-model",
        "source": rgb["source"],
        "provider": rgb["provider"],
        "capability": rgb["capability"],
        "zones": rgb["zones"],
        "zone_policy": rgb["zone_policy"],
        "brightness": rgb["brightness"],
        "update_policy": rgb["update_policy"],
        "identities": rgb["identities"],
    }

    return json.dumps(
        payload,
        indent=2,
        sort_keys=True,
    ) + "\n"


def outputs(visual: dict[str, Any]) -> dict[str, str]:
    c = palette(visual)

    return {
        "hyperlab-palette-quickshell.json": quickshell(c),
        "hyperlab-palette-gtk.css": css_tokens(c, "gtk"),
        "hyperlab-palette-waybar.css": css_tokens(c, "waybar"),
        "hyperlab-palette.rasi": rofi(c),
        "hyperlab-palette-foot.ini": foot(c),
        "hyperlab-palette-kitty.conf": kitty(c),
        "hyperlab-palette-hyprland.lua": hyprland(c),
        "hyperlab-palette.sway": sway(c),
        "hyperlab-palette-swaylock.conf": swaylock(c),
        "hyperlab-rgb-map.json": rgb_map(visual),
    }


