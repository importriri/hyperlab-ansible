#!/usr/bin/env python3
"""Keep development-process attribution out of public repository content."""

from __future__ import annotations

import ast
import re
import shlex
import subprocess
from pathlib import Path


ROOT = Path(__file__).resolve().parents[1]

# Split tokens deliberately: the guard must not contain the exact strings it
# rejects, otherwise it would fail on its own source.
FORBIDDEN = (
    "clau" + "de",
    "chat" + "gpt",
    "open" + "ai",
    "anth" + "ropic",
    "co" + "dex",
    "github " + "copilot",
    "a" + "i-" + "generated",
    "a" + "i " + "generated",
    "generated by " + "a" + "i",
    "a" + "i " + "assistant",
    "chat " + "bridge",
)

# The service VM connection user follows the configured admin account. A
# literal name here would publish one machine's account and ignore the
# setting an operator changes.
INVENTORY = "inventory.ini"
SERVICE_GROUP = "services"
SERVICE_HOST = "svc-jellyfin"
CONNECTION_USER_KEYS = (
    "ansible_user",
    "ansible_ssh_user",
)
CONNECTION_USER = "{{ admin_user }}"
UNPARSABLE = object()
SECTION = re.compile(
    r"^\[([^\[\]:\s]+)(?::(\w+))?\]$"
)

LOCAL_ONLY = {
    "HYPERLAB-CURRENT-HANDOFF.md",
}


def repository_paths() -> list[Path]:
    result = subprocess.run(
        [
            "git",
            "ls-files",
            "-c",
            "-o",
            "--exclude-standard",
        ],
        cwd=ROOT,
        text=True,
        capture_output=True,
        check=True,
    )

    paths = []

    for relative in result.stdout.splitlines():
        if not relative:
            continue

        if relative in LOCAL_ONLY:
            continue

        path = ROOT / relative

        if path.is_file():
            paths.append(
                path
            )

    return paths


def readable_text(
    path: Path,
) -> str | None:
    data = path.read_bytes()

    if b"\0" in data:
        return None

    try:
        return data.decode(
            "utf-8"
        )
    except UnicodeDecodeError:
        return None


def inventory_value(
    raw: str,
) -> object:
    # The INI inventory plugin turns a value into a Python literal when it
    # can and keeps the string otherwise. Any other evaluation error makes
    # the plugin reject the whole inventory: "{{ 'name' }}" is a set inside
    # a set, a TypeError, not a string.
    try:
        return ast.literal_eval(
            raw
        )
    except (ValueError, SyntaxError):
        return raw
    except (TypeError, RecursionError, MemoryError):
        return UNPARSABLE


def inventory_identity_failures() -> list[tuple[str, int, str]]:
    path = ROOT / INVENTORY

    try:
        content = path.read_text(
            encoding="utf-8"
        )
    except (OSError, UnicodeDecodeError):
        return [
            (
                INVENTORY,
                0,
                "inventory is unreadable",
            )
        ]

    failures = []
    service_lines = []
    group = "ungrouped"
    state = "hosts"

    for number, line in enumerate(
        content.splitlines(),
        start=1,
    ):
        stripped = line.strip()

        if not stripped or stripped[0] in "#;":
            continue

        section = SECTION.match(
            stripped
        )

        if section:
            group = section.group(1)
            state = section.group(2) or "hosts"
            continue

        if state == "children":
            continue

        if state == "vars":
            if "=" not in stripped:
                failures.append(
                    (
                        INVENTORY,
                        number,
                        "group variable is not key=value",
                    )
                )
                continue

            key, raw = (
                part.strip()
                for part in stripped.split(
                    "=",
                    1,
                )
            )
            assignments = [
                (key, raw)
            ]
            host = None
        else:
            try:
                tokens = shlex.split(
                    stripped,
                    comments=True,
                )
            except ValueError:
                failures.append(
                    (
                        INVENTORY,
                        number,
                        "host line does not parse",
                    )
                )
                continue

            host = tokens[0]
            assignments = []

            for token in tokens[1:]:
                if "=" not in token:
                    failures.append(
                        (
                            INVENTORY,
                            number,
                            "host variable is not key=value",
                        )
                    )
                    continue

                key, raw = token.split(
                    "=",
                    1,
                )
                assignments.append(
                    (key, raw)
                )

        users = [
            inventory_value(raw)
            for key, raw in assignments
            if key in CONNECTION_USER_KEYS
        ]

        for user in users:
            if user is UNPARSABLE:
                failures.append(
                    (
                        INVENTORY,
                        number,
                        "connection user does not parse",
                    )
                )
            elif user != CONNECTION_USER:
                failures.append(
                    (
                        INVENTORY,
                        number,
                        "connection user is not the admin_user setting",
                    )
                )

        if host == SERVICE_HOST and group == SERVICE_GROUP:
            service_lines.append(
                (number, len(users))
            )

    if len(service_lines) != 1:
        failures.append(
            (
                INVENTORY,
                0,
                f"{SERVICE_HOST} is defined {len(service_lines)} times "
                f"in [{SERVICE_GROUP}]",
            )
        )
    else:
        number, count = service_lines[0]

        if count != 1:
            failures.append(
                (
                    INVENTORY,
                    number,
                    f"{SERVICE_HOST} sets its connection user "
                    f"{count} times",
                )
            )

    return failures


def main() -> int:
    failures = []

    for path in repository_paths():
        content = readable_text(
            path
        )

        if content is None:
            continue

        for number, line in enumerate(
            content.splitlines(),
            start=1,
        ):
            lowered = line.lower()

            for marker in FORBIDDEN:
                if marker in lowered:
                    failures.append(
                        (
                            path.relative_to(ROOT),
                            number,
                        )
                    )

    identity_failures = inventory_identity_failures()

    for path, line, reason in identity_failures:
        print(
            f"FAIL public connection identity: "
            f"{path}:{line}: {reason}"
        )

    if failures:
        for path, line in failures:
            print(
                f"FAIL public process metadata: "
                f"{path}:{line}"
            )

    if failures or identity_failures:
        raise SystemExit(
            "public repository process hygiene contract failed"
        )

    print(
        "Public repository process hygiene contract: OK"
    )

    return 0


if __name__ == "__main__":
    raise SystemExit(
        main()
    )
